#!/usr/bin/env node
/**
 * Regenerates lib/threeTryOn/faceMeshTriangles.ts — the triangle list of
 * MediaPipe's 468-point face mesh, used to build the depth-only face
 * occluder in the 3D try-on.
 *
 *   node scripts/generate-face-mesh-triangles.mjs
 *
 * @mediapipe/tasks-vision exposes the mesh only as edges
 * (`FaceLandmarker.FACE_LANDMARKS_TESSELATION`), not as faces, and shipping
 * the library into the try-on bundle just for a constant would be wasteful.
 * On a triangulated surface every face is a 3-clique of its edge graph, so
 * the faces are recovered from the edges here, once, at development time.
 *
 * The tessellation leaves the eyes and mouth as holes. An occluder with holes
 * in it would let the far temple arm show through the far eye opening, so
 * every inner boundary loop is closed with a fan. The outer face-oval
 * boundary is the longest loop and is left open.
 */

import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";

const bundle = resolve("node_modules/@mediapipe/tasks-vision/vision_bundle.mjs");
const { FaceLandmarker } = await import(pathToFileURL(bundle).href);
const edges = FaceLandmarker.FACE_LANDMARKS_TESSELATION;

const adjacency = new Map();
const link = (a, b) => {
  if (!adjacency.has(a)) adjacency.set(a, new Set());
  adjacency.get(a).add(b);
};
for (const { start, end } of edges) {
  link(start, end);
  link(end, start);
}

const triangles = [];
for (const [a, neighbours] of adjacency) {
  for (const b of neighbours) {
    if (b <= a) continue;
    for (const c of adjacency.get(b)) {
      if (c > b && neighbours.has(c)) triangles.push([a, b, c]);
    }
  }
}

// Boundary edges (used by exactly one triangle) chain into loops.
const edgeUse = new Map();
const key = (p, q) => (p < q ? `${p}-${q}` : `${q}-${p}`);
for (const [a, b, c] of triangles) {
  for (const [p, q] of [[a, b], [b, c], [a, c]]) edgeUse.set(key(p, q), (edgeUse.get(key(p, q)) ?? 0) + 1);
}
const boundary = new Map();
const addBoundary = (p, q) => {
  if (!boundary.has(p)) boundary.set(p, []);
  boundary.get(p).push(q);
};
for (const [k, n] of edgeUse) {
  if (n !== 1) continue;
  const [p, q] = k.split("-").map(Number);
  addBoundary(p, q);
  addBoundary(q, p);
}

const loops = [];
const seen = new Set();
for (const start of boundary.keys()) {
  if (seen.has(start)) continue;
  const loop = [start];
  seen.add(start);
  let previous = -1;
  let current = start;
  for (;;) {
    const next = boundary.get(current).find((v) => v !== previous && !seen.has(v));
    if (next === undefined) break;
    loop.push(next);
    seen.add(next);
    previous = current;
    current = next;
  }
  loops.push(loop);
}
loops.sort((x, y) => y.length - x.length);
const outer = loops.shift();

let filled = 0;
for (const loop of loops) {
  for (let i = 1; i < loop.length - 1; i++) {
    triangles.push([loop[0], loop[i], loop[i + 1]]);
    filled++;
  }
}

const flat = triangles.flat();
const body = `import type { } from "react";

/**
 * Triangle indices of MediaPipe's 468-point face mesh (${triangles.length} triangles:
 * ${triangles.length - filled} from the library's tessellation, ${filled} closing the eye and
 * mouth openings). Generated by scripts/generate-face-mesh-triangles.mjs —
 * regenerate rather than edit.
 */
export const FACE_MESH_TRIANGLES: Uint16Array = new Uint16Array([${flat.join(",")}]);
`.replace('import type { } from "react";\n\n', "");
writeFileSync("lib/threeTryOn/faceMeshTriangles.ts", body);
console.log(
  `triangles: ${triangles.length} (${triangles.length - filled} tessellation + ${filled} hole fill); ` +
    `outer boundary: ${outer.length} vertices; inner holes closed: ${loops.length} (sizes ${loops.map((l) => l.length).join(", ")})`
);
